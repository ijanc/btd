struct ev {
	int	 kbd;
	u_int	 type;
	int	 value;
};

static struct ev	 got[64];
static int		 ngot;
static int		 failed;

int
engine_imsg_compose_bus(int type, void *data, uint16_t len)
{
	struct wscons_event	*e = data;
	size_t			 i;

	for (i = 0; i < len / sizeof(*e) && ngot < (int)nitems(got); i++) {
		got[ngot].kbd = type == IMSG_WSKBD;
		got[ngot].type = e[i].type;
		got[ngot].value = e[i].value;
		ngot++;
	}
	return (0);
}

static void
check(const char *name, struct hid *hid, uint8_t id, const uint8_t *r,
    size_t len, const struct ev *exp, int nexp)
{
	int	 i;

	ngot = 0;
	hid_report(hid, id, r, len);
	if (ngot == nexp && memcmp(got, exp, nexp * sizeof(*exp)) == 0) {
		printf("%s: ok\n", name);
		return;
	}
	printf("%s: FAILED\n", name);
	for (i = 0; i < ngot; i++)
		printf("  got %s %u %d\n", got[i].kbd ? "kbd" : "mouse",
		    got[i].type, got[i].value);
	for (i = 0; i < nexp; i++)
		printf("  exp %s %u %d\n", exp[i].kbd ? "kbd" : "mouse",
		    exp[i].type, exp[i].value);
	failed = 1;
}

static void
test_mouse(void)
{
	struct hid	*hid;
	const uint8_t	 move[] = { 0x01, 0x00, 0x05, 0xd0, 0xff, 0x01, 0x00 };
	const uint8_t	 up[] = { 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00 };
	const struct ev	 exp_move[] = {
		{ 0, WSCONS_EVENT_MOUSE_DOWN, 0 },
		{ 0, WSCONS_EVENT_MOUSE_DELTA_X, 5 },
		{ 0, WSCONS_EVENT_MOUSE_DELTA_Y, 3 },
		{ 0, WSCONS_EVENT_MOUSE_DELTA_Z, -1 },
		{ 0, WSCONS_EVENT_SYNC, 0 },
	};
	const struct ev	 exp_up[] = {
		{ 0, WSCONS_EVENT_MOUSE_UP, 0 },
		{ 0, WSCONS_EVENT_SYNC, 0 },
	};

	if ((hid = hid_new(mouse_map, sizeof(mouse_map), WSKBD_TYPE_PC_XT)) ==
	    NULL)
		errx(1, "mouse map");
	printf("mouse: %s\n", hid_describe(hid));
	check("mouse move", hid, 2, move, sizeof(move), exp_move,
	    nitems(exp_move));
	check("mouse up", hid, 2, up, sizeof(up), exp_up, nitems(exp_up));
	hid_free(hid);
}

static void
test_kbd(int type, const char *name, int shift, int a)
{
	struct hid	*hid;
	char		 n[64];
	const uint8_t	 down[] = { 0x02, 0x04, 0, 0, 0, 0, 0 };
	const uint8_t	 up[] = { 0x00, 0x00, 0, 0, 0, 0, 0 };
	const struct ev	 exp_down[] = {
		{ 1, WSCONS_EVENT_KEY_DOWN, shift },
		{ 1, WSCONS_EVENT_KEY_DOWN, a },
	};
	const struct ev	 exp_up[] = {
		{ 1, WSCONS_EVENT_KEY_UP, a },
		{ 1, WSCONS_EVENT_KEY_UP, shift },
	};

	if ((hid = hid_new(kbd_map, sizeof(kbd_map), type)) == NULL)
		errx(1, "keyboard map");
	printf("keyboard: %s\n", hid_describe(hid));
	snprintf(n, sizeof(n), "%s shift a down", name);
	check(n, hid, 1, down, sizeof(down), exp_down, nitems(exp_down));
	snprintf(n, sizeof(n), "%s shift a up", name);
	check(n, hid, 1, up, sizeof(up), exp_up, nitems(exp_up));
	hid_free(hid);
}

static void
test_leds(void)
{
	struct hid	*hid;
	uint8_t		 buf[8], id;
	int		 len;

	if ((hid = hid_new(kbd_map, sizeof(kbd_map), WSKBD_TYPE_USB)) == NULL)
		errx(1, "keyboard map");
	len = hid_leds(hid, WSKBD_LED_CAPS, &id, buf, sizeof(buf));
	if (len == 1 && id == 1 && buf[0] == 0x02)
		printf("leds caps: ok\n");
	else {
		printf("leds caps: FAILED, len %d id %u 0x%02x\n", len, id,
		    buf[0]);
		failed = 1;
	}
	len = hid_leds(hid, WSKBD_LED_NUM | WSKBD_LED_SCROLL, &id, buf,
	    sizeof(buf));
	if (len == 1 && id == 1 && buf[0] == 0x05)
		printf("leds num scroll: ok\n");
	else {
		printf("leds num scroll: FAILED, len %d id %u 0x%02x\n", len,
		    id, buf[0]);
		failed = 1;
	}
	hid_free(hid);

	if ((hid = hid_new(mouse_map, sizeof(mouse_map), WSKBD_TYPE_USB)) ==
	    NULL)
		errx(1, "mouse map");
	if (hid_leds(hid, WSKBD_LED_CAPS, &id, buf, sizeof(buf)) == -1)
		printf("leds mouse: ok\n");
	else {
		printf("leds mouse: FAILED\n");
		failed = 1;
	}
	hid_free(hid);
}

/*
 * A key array whose size times count wraps to zero in 32 bits must be
 * dropped, not read past the report.
 */
static void
test_hostile(void)
{
	static uint8_t	 map[] = {
		0x05, 0x01, 0x09, 0x06, 0xa1, 0x01, 0x05, 0x07,
		0x19, 0x00, 0x29, 0xff, 0x15, 0x00, 0x26, 0xff,
		0x00, 0x75, 0x04, 0x97, 0x00, 0x00, 0x00, 0x40,
		0x81, 0x00, 0xc0,
	};
	struct hid	*hid;
	const uint8_t	 r[] = { 0x11, 0x11, 0x11, 0x11 };
	const struct ev	 none[1] = { { 0, 0, 0 } };

	if ((hid = hid_new(map, sizeof(map), WSKBD_TYPE_USB)) == NULL)
		errx(1, "hostile map");
	check("hostile map", hid, 0, r, sizeof(r), none, 0);
	hid_free(hid);
}

int
main(void)
{
	test_mouse();
	test_kbd(WSKBD_TYPE_PC_XT, "xt", 0x2a, 0x1e);
	test_kbd(WSKBD_TYPE_USB, "usb", 0xe1, 0x04);
	test_leds();
	test_hostile();
	return (failed);
}
