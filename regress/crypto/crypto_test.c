static void
test_ecdh(void)
{
	void	*a, *b;
	uint8_t	 pa[64], pb[64], ka[32], kb[32];

	if ((a = crypto_ecdh_new(pa)) == NULL ||
	    (b = crypto_ecdh_new(pb)) == NULL)
		errx(1, "ecdh new");
	if (crypto_ecdh_shared(a, pb, ka) == -1 ||
	    crypto_ecdh_shared(b, pa, kb) == -1)
		errx(1, "ecdh shared");
	check("ecdh", ka, kb, sizeof(ka));
	pb[0] ^= 1;
	if (crypto_ecdh_shared(a, pb, ka) != -1) {
		printf("ecdh off curve: FAILED\n");
		failed = 1;
	} else
		printf("ecdh off curve: ok\n");
	crypto_ecdh_free(a);
	crypto_ecdh_free(b);
}

int
main(void)
{
	test_ah();
	test_c1();
	test_s1();
	test_f4();
	test_f5();
	test_f6();
	test_g2();
	test_h6();
	test_ecdh();
	return (failed);
}
