static int	 failed;

static void
check(const char *name, const uint8_t *got, const uint8_t *exp, size_t len)
{
	size_t	 i;

	if (memcmp(got, exp, len) == 0) {
		printf("%s: ok\n", name);
		return;
	}
	printf("%s: FAILED\n  got ", name);
	for (i = 0; i < len; i++)
		printf("%02x", got[i]);
	printf("\n  exp ");
	for (i = 0; i < len; i++)
		printf("%02x", exp[i]);
	printf("\n");
	failed = 1;
}

